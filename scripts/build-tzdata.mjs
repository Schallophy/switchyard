// 生成 src/ui/js/tzdata.js。数据来自 IANA tz database 的发布版本：
//   zone1970.tab  自 1970 年起民用时间一致的代表时区（已按规则去重）
//   backward      历史名称与别名
//   etcetera      UTC/GMT 的固定偏移别名
// 用法：node scripts/build-tzdata.mjs [版本，默认 2026f]

import { writeFile } from "node:fs/promises";
import path from "node:path";

const ref = process.argv[2] || "2026f";
const base = `https://raw.githubusercontent.com/eggert/tz/${ref}`;
const files = ["zone1970.tab", "backward", "etcetera"];
const target = path.join(import.meta.dirname, "..", "src", "ui", "js", "tzdata.js");

function rows(text) {
  return text
    .split("\n")
    .filter((line) => line && !line.startsWith("#"));
}

function links(text) {
  const out = new Map();
  for (const line of rows(text)) {
    const match = /^Link\s+(\S+)\s+(\S+)/.exec(line);
    if (!match) continue;
    const [, canonical, alias] = match;
    out.set(alias, canonical === "Etc/UTC" || canonical === "Etc/GMT" ? "UTC" : canonical);
  }
  return out;
}

const sources = {};
for (const file of files) {
  const response = await fetch(`${base}/${file}`);
  if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
  sources[file] = await response.text();
}

const zones = rows(sources["zone1970.tab"]).map((line) => {
  const [countries, , zone, comment = ""] = line.split("\t");
  return { zone, countries: countries.replaceAll(",", " "), comment };
});
zones.push({ zone: "UTC", countries: "", comment: "" });
zones.sort((left, right) => left.zone.localeCompare(right.zone));

const known = new Set(zones.map((zone) => zone.zone));
const aliases = new Map([...links(sources.backward), ...links(sources.etcetera)]);
for (const [alias, canonical] of aliases) {
  if (!known.has(canonical)) throw new Error(`${alias}: unknown target ${canonical}`);
  if (alias !== canonical && known.has(alias)) {
    throw new Error(`${alias}: alias shadows a representative zone`);
  }
  if (alias === canonical) aliases.delete(alias);
}
const aliasEntries = [...aliases].sort(([left], [right]) => left.localeCompare(right));

const quote = (value) => JSON.stringify(value);
const body = zones
  .map(
    ({ zone, countries, comment }) =>
      `  [${quote(zone)}, ${quote(countries)}${comment ? `, ${quote(comment)}` : ""}],`,
  )
  .join("\n");
const aliasBody = aliasEntries.map(([alias, canonical]) => `  ${quote(alias)}: ${quote(canonical)},`);

const output = `// Generated by scripts/build-tzdata.mjs from IANA tz database ${ref}.
// zone1970.tab: one representative per timezone whose civil time has agreed since 1970.
// backward + etcetera: aliases, resolved to a representative so each timezone is listed once.
// Do not edit by hand.

export const TZ_ZONES = [
${body}
];

export const TZ_ALIASES = {
${aliasBody.join("\n")}
};
`;

await writeFile(target, output);
console.log(`wrote ${target}: ${zones.length} zones, ${aliasEntries.length} aliases (tzdb ${ref})`);
